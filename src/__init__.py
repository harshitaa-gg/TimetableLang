# TimetableLang compiler front-end package (Phase 1).
#
# This package contains the Phase 1 components of the TimetableLang
# compiler:
#   - tokens.py     : Token and TokenType definitions
#   - lexer.py       : Lexical analyzer (source code -> tokens)
#   - ast_nodes.py   : Abstract Syntax Tree node classes
#   - parser.py      : Recursive-descent parser (tokens -> AST)
#
# Phase 2 (semantic analysis, symbol tables, conflict detection) and
# Phase 3 (timetable generation) are NOT part of this package yet.
